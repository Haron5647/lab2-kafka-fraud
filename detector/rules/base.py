"""Общий интерфейс правил детекции.

Правила ничего не знают про Kafka: они получают объект Transaction и возвращают
Alert или None. Благодаря этому их можно тестировать обычными юнит-тестами.

Жизненный цикл одной транзакции в детекторе:
    1. для каждого правила вызывается ``check(tx)`` — решает, подозрительна ли операция;
    2. если ни одно правило не сработало, вызывается ``commit(tx)`` — правило
       «запоминает» легитимную операцию в своём состоянии (окно, средний чек, города).
Подозрительные операции в историю НЕ попадают, чтобы мошенник не «сдвинул» среднюю.
"""
from __future__ import annotations

from abc import ABC, abstractmethod

from common.models import Alert, Transaction


class Rule(ABC):
    name: str = "rule"

    @abstractmethod
    def check(self, tx: Transaction) -> Alert | None:
        """Проверить транзакцию. Не должна учитывать саму tx в состоянии правила."""

    @abstractmethod
    def commit(self, tx: Transaction) -> None:
        """Учесть легитимную транзакцию в состоянии правила."""
